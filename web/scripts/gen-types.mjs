// Generates src/lib/types.ts from data/schema/*.json (the source of truth).
// All schemas are merged into a single namespace of $defs so shared types are emitted once.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const schemaDir = fileURLToPath(new URL('../../data/schema/', import.meta.url));
const target = fileURLToPath(new URL('../src/lib/types.ts', import.meta.url));

// Root type of each file. promocion.schema.json is just a $ref to its own $defs/promocion.
const ROOTS = {
  'promociones.schema.json': 'PromocionesFile',
  'source.schema.json': 'SourceFile',
  'state.schema.json': 'State',
  'overrides.schema.json': 'OverridesFile',
  'iprem.schema.json': 'IpremFile',
  'programas.schema.json': 'ProgramasFile',
  'fuentes.schema.json': 'FuentesFile',
  'municipios.schema.json': 'MunicipiosFile',
};
// $defs whose default name would be unclear or clash across files.
const RENAMES = {
  'state.schema.json#fuente': 'EstadoFuente',
  'state.schema.json#documento': 'DocumentoEstado',
  'fuentes.schema.json#fuente': 'Fuente',
  'programas.schema.json#programa': 'ReglaPrograma',
};

const pascal = (name) => name.replace(/(^|[-_])([a-z])/g, (_, __, c) => c.toUpperCase());
const files = readdirSync(schemaDir).filter((f) => f.endsWith('.schema.json'));
const schemas = Object.fromEntries(
  files.map((f) => [f, JSON.parse(readFileSync(schemaDir + f, 'utf8'))]),
);

const typeName = (file, key) => RENAMES[`${file}#${key}`] ?? pascal(key);

function rewrite(node, file) {
  if (Array.isArray(node)) return node.map((n) => rewrite(n, file));
  if (node === null || typeof node !== 'object') return node;
  if (typeof node.$ref === 'string') {
    const [other, pointer = ''] = node.$ref.split('#');
    const refFile = other || file;
    const key = pointer.replace('/$defs/', '');
    const name = key ? typeName(refFile, key) : refFile === 'promocion.schema.json' ? 'Promocion' : ROOTS[refFile];
    return { $ref: `#/$defs/${name}` };
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (['$schema', '$id', '$defs', 'title', 'description', '$comment'].includes(k)) continue;
    // Property names such as "title" or "description" must survive.
    out[k] = k === 'properties'
      ? Object.fromEntries(Object.entries(v).map(([p, s]) => [p, rewrite(s, file)]))
      : rewrite(v, file);
  }
  return out;
}

const defs = {};
const add = (name, schema) => {
  if (defs[name]) throw new Error(`Nombre de tipo repetido: ${name}`);
  defs[name] = { ...schema, title: name };
};
for (const [file, schema] of Object.entries(schemas)) {
  for (const [key, def] of Object.entries(schema.$defs ?? {})) add(typeName(file, key), rewrite(def, file));
  if (ROOTS[file]) add(ROOTS[file], rewrite(schema, file));
}

const root = {
  title: 'Schemas',
  type: 'object',
  additionalProperties: false,
  required: Object.values(ROOTS),
  properties: Object.fromEntries(Object.values(ROOTS).map((n) => [n, { $ref: `#/$defs/${n}` }])),
  $defs: defs,
};

const output = await compile(root, 'Schemas', {
  bannerComment:
    '/* eslint-disable */\n// GENERATED by `npm run gen:types` from data/schema/. Do not edit by hand.',
  unreachableDefinitions: true,
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  format: true,
  style: { singleQuote: true, printWidth: 110 },
});
writeFileSync(target, output.replace(/\r\n/g, '\n'));
console.log(`Escrito ${target}`);
